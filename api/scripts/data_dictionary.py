def _type(column: Column) -> str:
    return column.type.compile(dialect=postgresql.dialect()).lower()


def _keys(column: Column) -> str:
    keys = []
    if column.primary_key:
        keys.append("PK")
    keys += [f"FK → {fk.target_fullname}" for fk in column.foreign_keys]
    if column.unique:
        keys.append("UNIQUE")
    if column.index:
        keys.append("INDEX")
    return ", ".join(keys)


def _default(column: Column) -> str:
    if column.server_default is None:
        return ""
    if column.identity is not None:
        return "`generated always as identity`"
    return f"`{column.server_default.arg}`"


def _rules(table: Table) -> list[str]:
    rules = []
    for con in sorted(table.constraints, key=lambda c: c.name or ""):
        if isinstance(con, ExcludeConstraint):
            parts = ", ".join(f"{expr} WITH {op}" for expr, _, op in con._render_exprs)
            rules.append(f"`{con.name}`: `EXCLUDE USING {con.using} ({parts}) WHERE ({con.where})`")
        elif isinstance(con, CheckConstraint):
            rules.append(f"`{con.name}`: `CHECK ({con.sqltext})`")
    return rules


def check_descriptions() -> None:
    """Every column must be described, and no description may point to a missing column."""
    real = {(t.name, c.name) for t in Base.metadata.tables.values() for c in t.columns}
    missing = sorted(real - COLUMNS.keys())
    extra = sorted(COLUMNS.keys() - real)
    tables_missing = sorted(set(Base.metadata.tables) - TABLES.keys())
    if missing or extra or tables_missing:
        raise SystemExit(
            f"Update scripts/data_dictionary.py. Columns without a description: {missing}. "
            f"Described columns that do not exist: {extra}. Tables: {tables_missing}."
        )


def render() -> str:
    check_descriptions()
    lines = [
        "# Data dictionary — Clinique Physio Mont-Royal",
        "",
        "Status: **D1 (v0.1.0)**. Generated from the code by `api/scripts/data_dictionary.py`;",
        "do not edit by hand. Run `python -m scripts.data_dictionary` in `api/` after changing a model.",
        "",
        "Related: [erd.md](erd.md) (diagrams), [data-classification.md](data-classification.md)",
        "(privacy classes and who may see what), [architecture.md](architecture.md).",
        "",
        "## Conventions",
        "",
        "| Rule | Detail |",
        "|---|---|",
        "| Identifiers | UUID generated by PostgreSQL (`gen_random_uuid()`): not guessable, unlike 1, 2, 3 |",
        "| Dates and times | `timestamp with time zone`, stored in UTC, shown in Montréal time (ADR-004) |",
        "| Time ranges | `tstzrange` (start included, end excluded), so 10:00–10:30 and 10:30–11:00 do not overlap |",
        "| Money | Integer cents (`12000` = 120,00 $), never floating point |",
        "| Encrypted fields | Names end in `_enc`: `bytea` encrypted by the API (Fernet), key outside the database |",
        "| Secrets | Tokens and passwords are stored only as hashes (Argon2id or SHA-256) |",
        "| Required | **Yes** = `NOT NULL` in the database |",
        "| Privacy class | Public, Internal, Personal, Health or Secret, as defined in data-classification.md |",
        "",
        "## Tables",
        "",
        "| Table | Module | Purpose | Requirements |",
        "|---|---|---|---|",
    ]
    tables = list(TABLES)
    for name in tables:
        module, purpose, req = TABLES[name]
        lines.append(f"| [`{name}`](#{name}) | {module} | {purpose} | {req} |")

    for name in tables:
        table = Base.metadata.tables[name]
        module, purpose, req = TABLES[name]
        lines += [
            "",
            f"### {name}",
            "",
            f"{purpose} ({req})",
            "",
            "| Column | Type | Required | Default | Keys | Description | Class |",
            "|---|---|---|---|---|---|---|",
        ]
        for column in table.columns:
            description, privacy = COLUMNS[(name, column.name)]
            required = "No" if column.nullable else "Yes"
            lines.append(
                f"| `{column.name}` | {_type(column)} | {required} | {_default(column)} "
                f"| {_keys(column)} | {description} | {privacy} |"
            )
        rules = _rules(table)
        if rules:
            lines += ["", "Rules enforced by the database:", ""]
            lines += [f"- {rule}" for rule in rules]

    lines += [
        "",
        "## Planned tables",
        "",
        "Designed in [erd.md](erd.md), added with the features that need them.",
        "",
        "| Table | Content | Deliverable |",
        "|---|---|---|",
    ]
    lines += [f"| `{t}` | {c} | {d} |" for t, c, d in PLANNED]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Written: {OUTPUT}")
